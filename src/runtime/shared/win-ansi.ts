// WinAnsiEncoding (ISO 32000-1, D.2): the encoding of the standard fonts and
// of a form field's text. Latin-1 from 0x20 to 0x7E and from 0xA0 to 0xFF,
// and 27 characters above 0xFF that take codes between 0x80 and 0x9F.

/** Unicode code points above 0xFF and their WinAnsi code (0x80 to 0x9F). */
export const WIN_ANSI: ReadonlyMap<number, number> = new Map([[0x152, 0x8C], [0x153, 0x9C], [0x160, 0x8A], [0x161, 0x9A], [0x178, 0x9F], [0x17D, 0x8E], [0x17E, 0x9E], [0x192, 0x83], [0x2C6, 0x88], [0x2DC, 0x98], [0x2013, 0x96], [0x2014, 0x97], [0x2018, 0x91], [0x2019, 0x92], [0x201A, 0x82], [0x201C, 0x93], [0x201D, 0x94], [0x201E, 0x84], [0x2020, 0x86], [0x2021, 0x87], [0x2022, 0x95], [0x2026, 0x85], [0x2030, 0x89], [0x2039, 0x8B], [0x203A, 0x9B], [0x20AC, 0x80], [0x2122, 0x99]])

/** The WinAnsi code of one character, or `undefined` when the encoding has none. */
export const winAnsiCode = (character: string): number | undefined => {
  const point = character.codePointAt(0)!
  if ((point >= 0x20 && point <= 0x7E) || (point >= 0xA0 && point <= 0xFF)) return point
  return WIN_ANSI.get(point)
}
